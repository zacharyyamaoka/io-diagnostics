"""The host's default diagnostics set, one TOML file per part type (``io_diagnostics/diagnostics_default.d/``), written from the catalog.

Every catalog entry a live robot can be watched with (its ``consumers`` is ``robotdx`` or ``both``) becomes one ``[[diagnostic]]`` binding
with ``part = "<type>"`` and its default config written out in full (``robotdx/diagnostics/defaults.py``), so the file says every number
a person can change and where it came from. A ``[[part]]`` table per file says which entities are that part type. The ``sim2real``-only
entries (floors, twin ratios, clamp tests) are not bound here: they need datasets of runs, which a live host does not keep.

WHY generated, not hand-written: the numbers live once, in defaults.py; tests/test_default_diagnostics.py fails when a file drifts from
what this module writes. Regenerate:

    uv run --project /home/bam/io-diagnostics python -m io_diagnostics.default_diagnostics --write
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

from io_diagnostics.composite import toml_value
from io_diagnostics.stock_diagnostics import DEFAULT_DIR, _key, _plain
from robot_diagnostics import catalog
from robot_diagnostics.core import config_dict

WINDOW_S = 60
LIVE = ("robotdx", "both")

# Which entities are each part type. WHY these patterns: model_id is the robotparts id a driver reports (mjbots-moteus-c1,
# intel-realsense-d405); a composite (composition.toml) carries its kind; parts that are never a device of their own on this host (a
# gearbox, a whole servo joint, an arm) are composites. A RealSense is an RGB camera AND an RGBD one ("everything RGB has, plus depth").
REALSENSE = ["intel-realsense-d4*", "realsense-d4*"]
PART_MATCH: dict[str, dict[str, list[str]]] = {
    "servo": {"composite": ["servo", "joint", "station"]},
    "bldc_driver": {"model_id": ["mjbots-moteus-*", "odrive-*"]},
    "gearbox": {"composite": ["gearbox"]},
    "encoder": {"model_id": ["*as5047*", "*-encoder*"], "composite": ["encoder"]},
    "camera_rgb": {"model_id": [*REALSENSE, "obsbot-*", "logitech-*", "*-uvc-camera*"], "composite": ["camera"]},
    "camera_rgbd": {"model_id": REALSENSE, "composite": ["rgbd_camera"]},
    "camera_hsi": {"model_id": ["specim-*", "*-hyperspectral*"], "composite": ["hyperspectral_camera"]},
    "imu": {"model_id": ["*-imu*", "bosch-bno0*"], "composite": ["imu"]},
    "ft_sensor": {"model_id": ["ati-*", "*-load-cell*", "*-ft-sensor*"], "composite": ["ft_sensor", "load_cell"]},
    "gripper": {"model_id": ["robotiq-2f-*", "*-gripper*"], "composite": ["gripper", "claw"]},
    "arm": {"model_id": ["universal-robots-ur*"], "composite": ["arm"]},
    "arm_gripper": {"composite": ["arm_gripper", "pick", "picker"]},
    "deployment": {"composite": ["rack", "deployment", "cell"]},
}
# WHY "motor" for a driver board: the moteus driver reports its State in the group of that name; "" = the first group with the columns
STATE = {"bldc_driver": "motor"}


def bound(part: str) -> list:
    return [entry for entry in catalog.ENTRIES if entry.part == part and entry.consumers in LIVE]


def render() -> dict[str, str]:
    """``{file name: text}`` for every part type, in the catalog's order."""

    out = {}
    for number, (part, description) in enumerate(catalog.PARTS.items(), 1):
        entries = bound(part)
        skipped = [entry.id for entry in catalog.ENTRIES if entry.part == part and entry.consumers not in LIVE]
        lines = [f"# {description}",
                 "# GENERATED by io_diagnostics/default_diagnostics.py from robotdx/diagnostics/catalog.py + defaults.py; edit those, then",
                 "#   uv run --project /home/bam/io-diagnostics python -m io_diagnostics.default_diagnostics --write",
                 "# The host's default set (stock_diagnostics.py): read when the person has no diagnostics.toml of their own; the entity page's",
                 "# drill-in copies the whole set there the first time a value is changed. `limits:` says whose thresholds these are: his /",
                 "# his code gate; agent / proposed show as a warning at most, never a fail, until a person sets their own.",
                 f"# {len(entries)} bound here (live: consumers robotdx or both)"
                 + (f"; sim2real-only, not bound: {', '.join(skipped)}" if skipped else ""),
                 "", "[[part]]", f"type = {toml_value(part)}"]
        lines += [f"{name} = {toml_value(patterns)}" for name, patterns in PART_MATCH[part].items()]
        for entry in entries:
            found = catalog.default(entry.id)
            lines += ["", f"# {entry.checks}",
                      f"# from: {entry.prov} ({entry.where}); limits: {found.limits}" + (f" ({found.source})" if found.source else ""),
                      "[[diagnostic]]", f"id = {toml_value(entry.id)}", f"diagnostic = {toml_value(entry.primitive)}",
                      f"title = {toml_value(entry.title)}", f"part = {toml_value(part)}"]
            if STATE.get(part):
                lines.append(f"state = {toml_value(STATE[part])}")
            lines.append(f"window_s = {WINDOW_S}")
            # WHY only what differs from the dataclass: the drill-in marks a field "toml" when the file names it, so the file names exactly
            # the catalog's choices and the page's compact form shows those (the rest stay "default", one "Show all" away)
            own, base = config_dict(found.config), config_dict(type(found.config)())
            values = _plain({key: value for key, value in own.items() if value != base[key]})
            if values:
                lines += [f"[diagnostic.config]"] + [f"{_key(key)} = {toml_value(value)}" for key, value in values.items()]
        out[f"{number:02d}-{part}.toml"] = "\n".join(lines) + "\n"
    return out


def write(directory: Path = DEFAULT_DIR) -> list[Path]:
    directory.mkdir(parents=True, exist_ok=True)
    files = render()
    for stale in directory.glob("*.toml"):
        if stale.name not in files:
            stale.unlink()
    written = []
    for name, text in files.items():
        path = directory / name
        path.write_text(text)
        written.append(path)
    return written


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--write", action="store_true", help=f"write the files into {DEFAULT_DIR}")
    args = parser.parse_args(argv)
    if args.write:
        for path in write():
            print(path)
    else:
        for name, text in render().items():
            sys.stdout.write(f"### {name}\n{text}\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
